#include <iostream>
#include <cmath>

int main() {
   
    // Завдання 1 If27
   
    std::cout << "--- Завдання 1 ---\n";

    double x1;
    std::cout << "Введіть x: ";
    std::cin >> x1;

    int f;
    if (x1 < 0) {
        f = 0;
    } else {
        // Знаходимо цілу частину числа x
        int k = static_cast<int>(std::floor(x1));

        // Перевіряємо парність цілої частини:
        // якщо парна ([0,1), [2,3)...) -> 1, якщо непарна ([1,2), [3,4)...) -> -1
        if (k % 2 == 0) {
            f = 1;
        } else {
            f = -1;
        }
    }

    std::cout << "f(" << x1 << ") = " << f << "\n\n";

    
    // Завдання 2 18 вар.
  
    std::cout << "--- Завдання 2 ---\n";

    double r, x2, y2;
    std::cout << "Введіть радіус r (r > 0): ";
    std::cin >> r;

    std::cout << "Введіть x: ";
    std::cin >> x2;
    std::cout << "Введіть y: ";
    std::cin >> y2;

    // Точка належить помаранчевій області (II чверть), якщо:
    // 1. x <= 0 та y >= 0 (знаходження в II чверті)
    // 2. y <= x + r (обмеження гіпотенузою трикутника)
    bool isInside = (x2 <= 0) && (y2 >= 0) && (y2 <= x2 + r);

    if (isInside) {
        std::cout << "Точка (" << x2 << ", " << y2 << ") належить області.\n";
    } else {
        std::cout << "Точка (" << x2 << ", " << y2 << ") не належить області.\n";
    }

    return 0;
}
